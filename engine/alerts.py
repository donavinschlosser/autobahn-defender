"""
Autobahn Defender — Security alert model and JSONL storage.

Adapted from ai/alerts.py. Stores alerts generated by the deterministic
engine (CVE findings, network threats, hardening issues). Alerts have
severity levels, recommended actions (copy-paste commands), and lifecycle
states (active -> dismissed/resolved).

File: ~/.local/share/autobahn-defender/intel/alerts.jsonl
"""

from __future__ import annotations

import json
import logging
import os
import tempfile
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import INTEL_DIR

log = logging.getLogger(__name__)

ALERTS_FILE = INTEL_DIR / "alerts.jsonl"


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _ensure_dirs() -> None:
    INTEL_DIR.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(str(INTEL_DIR), 0o700)
    except OSError:
        pass


def create_alert(
    severity: str,
    title: str,
    recommended_action: str,
    affected_package: str = "",
    installed_version: str = "",
    patch_available: bool = False,
    alternative_action: str = "",
    source: str = "",
    cve_id: str = "",
) -> dict[str, Any]:
    """Create a new alert dict with auto-generated id and timestamp."""
    return {
        "id": str(uuid.uuid4()),
        "severity": severity.lower(),
        "title": title,
        "affected_package": affected_package,
        "installed_version": installed_version,
        "patch_available": patch_available,
        "recommended_action": recommended_action,
        "alternative_action": alternative_action,
        "source": source,
        "cve_id": cve_id,
        "timestamp": _now_iso(),
        "status": "active",
        "resolved_at": None,
    }


def add_alert(alert: dict[str, Any]) -> None:
    """Append an alert to the JSONL file (atomic append)."""
    _ensure_dirs()
    try:
        with open(ALERTS_FILE, "a") as f:
            f.write(json.dumps(alert, ensure_ascii=False) + "\n")
        os.chmod(str(ALERTS_FILE), 0o600)
    except Exception as e:
        log.error("Failed to write alert: %s", e)


def load_alerts(active_only: bool = True) -> list[dict[str, Any]]:
    """Load alerts from JSONL. If active_only, return only status='active'."""
    _ensure_dirs()
    if not ALERTS_FILE.exists():
        return []
    alerts = []
    try:
        for line in ALERTS_FILE.read_text().splitlines():
            line = line.strip()
            if line:
                alert = json.loads(line)
                if not active_only or alert.get("status") == "active":
                    alerts.append(alert)
    except Exception as e:
        log.error("Failed to load alerts: %s", e)
    return alerts


def resolve_alert(alert_id: str) -> bool:
    """Mark an alert as resolved."""
    _ensure_dirs()
    if not ALERTS_FILE.exists():
        return False
    alerts = []
    found = False
    try:
        for line in ALERTS_FILE.read_text().splitlines():
            line = line.strip()
            if line:
                alert = json.loads(line)
                if alert.get("id") == alert_id:
                    alert["status"] = "resolved"
                    alert["resolved_at"] = _now_iso()
                    found = True
                alerts.append(alert)
    except Exception as e:
        log.error("Failed to read alerts for resolve: %s", e)
        return False
    if found:
        _rewrite_alerts(alerts)
    return found


def dismiss_alert(alert_id: str) -> bool:
    """Mark an alert as dismissed (user acknowledges but doesn't fix)."""
    _ensure_dirs()
    if not ALERTS_FILE.exists():
        return False
    alerts = []
    found = False
    try:
        for line in ALERTS_FILE.read_text().splitlines():
            line = line.strip()
            if line:
                alert = json.loads(line)
                if alert.get("id") == alert_id:
                    alert["status"] = "dismissed"
                    alert["resolved_at"] = _now_iso()
                    found = True
                alerts.append(alert)
    except Exception as e:
        log.error("Failed to read alerts for dismiss: %s", e)
        return False
    if found:
        _rewrite_alerts(alerts)
    return found


def clear_resolved() -> int:
    """Remove resolved/dismissed alerts older than 90 days. Returns count removed."""
    _ensure_dirs()
    if not ALERTS_FILE.exists():
        return 0
    now = datetime.now(timezone.utc)
    alerts = []
    removed = 0
    try:
        for line in ALERTS_FILE.read_text().splitlines():
            line = line.strip()
            if line:
                alert = json.loads(line)
                if alert.get("status") in ("resolved", "dismissed"):
                    resolved_at = alert.get("resolved_at")
                    if resolved_at:
                        try:
                            dt = datetime.fromisoformat(resolved_at)
                            if (now - dt).days > 90:
                                removed += 1
                                continue
                        except Exception:
                            pass
                alerts.append(alert)
    except Exception as e:
        log.error("Failed to read alerts for cleanup: %s", e)
        return 0
    _rewrite_alerts(alerts)
    return removed


def _rewrite_alerts(alerts: list[dict[str, Any]]) -> None:
    """Atomically rewrite the alerts file."""
    _ensure_dirs()
    fd, tmp_path = tempfile.mkstemp(dir=str(INTEL_DIR), suffix=".tmp")
    try:
        with os.fdopen(fd, "w") as f:
            for alert in alerts:
                f.write(json.dumps(alert, ensure_ascii=False) + "\n")
        os.chmod(tmp_path, 0o600)
        os.replace(tmp_path, str(ALERTS_FILE))
    except Exception:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        raise